-- Миграция 18 (NR-038 п.1): точки изгиба связей карты, расставленные
-- владельцем двойным кликом по линии. Ключ связи устойчивый:
-- для связей из базы — «a|aPort|b|bPort» (как на карте), для
-- предполагаемых связей «устройство — шлюз», которые в базу не
-- пишутся и вычисляются при отдаче графа, — «assumed:<id
-- устройства>»: шлюз может смениться (ip:-узел станет устройством),
-- ключ связи остаётся тем же. Координаты — модельные координаты
-- карты, привязанные к мелкой сетке 20×20. Точки переживают
-- перезагрузку страницы, выход, перезапуск сервера и обновление
-- версии; при удалении связи или устройства записи стираются
-- (server/store: каскад в DeleteManualDevice/DeleteManualLink).
CREATE TABLE IF NOT EXISTS link_waypoints (
    link_key TEXT NOT NULL,
    idx      INTEGER NOT NULL,
    x        REAL NOT NULL,
    y        REAL NOT NULL,
    PRIMARY KEY (link_key, idx)
);
